def generate_jira_csv(project_data: dict) -> str:
    """
    Generate CSV formatted for Jira Project Import.
    Standard Jira headers: Summary, Description, Issue Type, Component/s, Priority, Original Estimate
    """
    output = io.StringIO()
    writer = csv.writer(output)
    
    # Header
    writer.writerow([
        "Issue Key",
        "Summary",
        "Description",
        "Issue Type",
        "Component/s",
        "Priority",
        "Original Estimate (hours)",
        "Status"
    ])
    
    tasks = project_data.get("tasks", [])
    for idx, task in enumerate(tasks, 1):
        summary = task.get("name", f"Task {idx}")
        component = task.get("component", "General")
        phase = task.get("phase", "Core Development")
        hours = task.get("estimated_hours", 4.0)
        status = str(task.get("status", "To Do")).replace("_", " ").title()
        
        description = (
            f"Phase: {phase}\n"
            f"Component: {component}\n"
            f"Estimated Effort: {hours} hours\n"
            f"Project: Plan #{project_data.get('id', '1')}"
        )
        
        # Jira issue type heuristically mapping
        issue_type = "Task"
        if "database" in component.lower() or "schema" in summary.lower():
            issue_type = "Technical Task"
        elif "ui" in component.lower() or "frontend" in component.lower():
            issue_type = "Story"
            
        writer.writerow([
            f"P2P-{idx}",
            summary,
            description,
            issue_type,
            component,
            "Medium",
            hours,
            status
        ])
        
    return output.getvalue()


def generate_github_csv(project_data: dict) -> str:
    """
    Generate CSV formatted for GitHub Issues Import (compatible with issue-importer tools).
    Headers: Title, Body, Labels, Milestone, State
    """
    output = io.StringIO()
    writer = csv.writer(output)
    
    writer.writerow(["Title", "Body", "Labels", "Milestone", "State"])
    
    tasks = project_data.get("tasks", [])
    for task in tasks:
        title = task.get("name", "Untitled Task")
        component = task.get("component", "General")
        phase = task.get("phase", "Core Dev")
        hours = task.get("estimated_hours", 4.0)
        status = task.get("status", "todo")
        
        body = (
            f"### Task Details\n"
            f"- **Component:** {component}\n"
            f"- **Phase:** {phase}\n"
            f"- **Estimated Hours:** {hours}h\n\n"
            f"Auto-generated by [Prompt2Plan](https://github.com/prompt2plan)"
        )
        
        labels = f"prompt2plan,{component.lower().replace(' ', '-')},{phase.lower().replace(' ', '-')}"
        state = "closed" if status == "done" else "open"
        
        writer.writerow([title, body, labels, phase, state])
        
    return output.getvalue()


